#!/usr/bin/env python3
"""
build_functional_assays.py — build the O10/B6 functional-assay reference from MaveDB.

SVIG-UK applies O10 (and B6) from "well-established in vitro or in vivo functional studies"
at variant level, with the operative criterion [S T1 O10, p.13]:

    "Variant is considered to have functionally abnormal effect if protein activity assay or
     functional impact is <25% of wildtype level."

The strength is not fixed by the guideline: it "should be determined according to the Clinical
Genome Resource (ClinGen) Sequence Variant Interpretation (SVI) recommendations", with
gene-specific guidance taking precedence, and the permitted range is very strong to supporting.
So the per-assay parameters live in the parameter table, where a laboratory records the
calibration decision it can defend, and this script only fetches the measurements.

Writes two files into reference_lists/:
    svig_uk_functional_assays.tsv         one row per assay: thresholds, strength, provenance
    svig_uk_functional_assay_scores.tsv   one row per variant: assay, protein change, % of WT

Usage:
    python3 utils/build_functional_assays.py            # refresh from MaveDB
    python3 utils/build_functional_assays.py --check    # verify the stored files, no network
"""
import argparse
import csv
import json
import os
import sys
import urllib.request

API = "https://api.mavedb.org/api/v1"
HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, "..", "reference_lists")
PARAMS = os.path.join(OUT_DIR, "svig_uk_functional_assays.tsv")
SCORES = os.path.join(OUT_DIR, "svig_uk_functional_assay_scores.tsv")

# Assays included, with the parameters SMART cannot derive from the guideline text.
#
# abnormal_max_pct comes straight from the guideline (<25% of wildtype).
# intermediate_max_pct and normal_min_pct are deliberately left empty: the guideline permits
# downgrading O10 for an intermediate result and applying B6 for "no damaging effect", but fixes
# no numeric boundary for either, so SMART applies neither until a laboratory records one.
# strength is the conservative end of what the guideline allows. SVIG-UK notes that MAVEs "often
# achieve a strong weighting"; raising this to STR is a calibration decision for the laboratory,
# to be recorded here with its justification.
ASSAYS = [{
    "assay_id": "TP53_transactivation_median",
    "gene": "TP53",
    "transcript": "NM_000546.6",
    "urn": "urn:mavedb:00001234-0-1",
    "metric": "median transcriptional activity, % of wild type, across eight promoter-specific "
              "yeast assays (p21WAF1, MDM2, BAX, GADD45, 14-3-3s, p53AIP1, Noxa, p53R2)",
    "abnormal_max_pct": "25",
    "intermediate_max_pct": "",
    "normal_min_pct": "",
    "strength": "MOD",
    "applies_to": "missense",
    "source": "Fortuno et al. 2021, An updated quantitative model to classify missense variants "
              "in the TP53 gene (ClinGen TP53 VCEP); scores via MaveDB",
    "pmid": "34273903",
    "licence": "CC0",
}]

PARAM_COLUMNS = ["assay_id", "gene", "transcript", "applies_to", "metric", "abnormal_max_pct",
                 "intermediate_max_pct", "normal_min_pct", "strength", "source", "pmid",
                 "licence", "urn"]

PARAM_HEADER = """\
# Functional-assay evidence for SVIG-UK O10 / B6 [S T1 O10 p.13; S T2 B6 p.17].
#
# The guideline's operative criterion is that a variant is functionally abnormal when protein
# activity is <25% of the wild-type level (abnormal_max_pct). Strength is NOT fixed by the
# guideline: it follows ClinGen SVI / CanVIG-UK calibration of the individual assay, with
# gene-specific guidance taking precedence, so it is recorded per assay below together with the
# justification. Permitted: VSTR, STR, MOD, SUPP.
#
# intermediate_max_pct and normal_min_pct are empty where the guideline fixes no boundary; the
# corresponding behaviour (downgraded O10, and B6) is then not applied at all.
#
# Regenerate with utils/build_functional_assays.py. Scores are in
# svig_uk_functional_assay_scores.tsv.
"""

SCORE_HEADER = """\
# Per-variant functional-assay measurements for O10 / B6. Assay parameters and provenance are in
# svig_uk_functional_assays.tsv. pct_wt is the assay's value as a percentage of wild-type
# activity. Generated by utils/build_functional_assays.py.
"""

THREE_TO_ONE = {
    "Ala": "A", "Arg": "R", "Asn": "N", "Asp": "D", "Cys": "C", "Gln": "Q", "Glu": "E",
    "Gly": "G", "His": "H", "Ile": "I", "Leu": "L", "Lys": "K", "Met": "M", "Phe": "F",
    "Pro": "P", "Ser": "S", "Thr": "T", "Trp": "W", "Tyr": "Y", "Val": "V", "Ter": "*",
}


def one_letter(hgvs_pro):
    """'p.Ala119Asp' -> 'A119D'; None when it is not a simple substitution."""
    text = str(hgvs_pro or "").strip()
    if not text.startswith("p."):
        return None
    body = text[2:].strip("()")
    if len(body) < 7:
        return None
    ref, pos, alt = body[:3], body[3:-3], body[-3:]
    if ref not in THREE_TO_ONE or alt not in THREE_TO_ONE or not pos.isdigit():
        return None
    if alt == "=" or ref == alt:
        return None
    return f"{THREE_TO_ONE[ref]}{pos}{THREE_TO_ONE[alt]}"


def fetch(url):
    with urllib.request.urlopen(url, timeout=120) as fh:
        return fh.read().decode()


def build():
    rows = []
    for assay in ASSAYS:
        meta = json.loads(fetch(f"{API}/score-sets/{assay['urn']}"))
        print(f"{assay['assay_id']}: {meta.get('title')} ({meta.get('numVariants')} variants, "
              f"licence {(meta.get('license') or {}).get('shortName')})")
        pubs = [p.get("identifier") for p in meta.get("primaryPublicationIdentifiers") or []]
        if assay["pmid"] not in pubs:
            sys.exit(f"{assay['assay_id']}: MaveDB reports publication(s) {pubs}, "
                     f"the table says {assay['pmid']} — check before using these scores")
        reader = csv.DictReader(fetch(f"{API}/score-sets/{assay['urn']}/scores").splitlines())
        kept = skipped = 0
        for r in reader:
            protein = one_letter(r.get("hgvs_pro"))
            score = r.get("score")
            if protein is None or score in (None, "", "NA"):
                skipped += 1
                continue
            rows.append({"assay_id": assay["assay_id"], "protein": protein,
                         "pct_wt": f"{float(score):.2f}"})
            kept += 1
        print(f"  {kept} substitutions kept, {skipped} rows skipped (not a simple substitution "
              f"or no score)")

    with open(PARAMS, "w", newline="") as fh:
        fh.write(PARAM_HEADER)
        w = csv.DictWriter(fh, PARAM_COLUMNS, delimiter="\t", extrasaction="ignore")
        w.writeheader()
        for assay in ASSAYS:
            w.writerow(assay)
    with open(SCORES, "w", newline="") as fh:
        fh.write(SCORE_HEADER)
        w = csv.DictWriter(fh, ["assay_id", "protein", "pct_wt"], delimiter="\t")
        w.writeheader()
        w.writerows(sorted(rows, key=lambda r: (r["assay_id"], r["protein"])))
    print(f"\nwritten: {PARAMS}\n         {SCORES} ({len(rows)} rows)")
    return rows


def check():
    """Summarise the stored files without touching the network."""
    for path in (PARAMS, SCORES):
        if not os.path.exists(path):
            sys.exit(f"missing: {path} — run without --check to build it")
    with open(PARAMS) as fh:
        params = list(csv.DictReader((l for l in fh if not l.startswith("#")), delimiter="\t"))
    with open(SCORES) as fh:
        scores = list(csv.DictReader((l for l in fh if not l.startswith("#")), delimiter="\t"))
    for p in params:
        mine = [float(s["pct_wt"]) for s in scores if s["assay_id"] == p["assay_id"]]
        cut = float(p["abnormal_max_pct"])
        print(f"{p['assay_id']}: {len(mine)} variants | {sum(1 for v in mine if v < cut)} below "
              f"{cut}% of wild type (functionally abnormal) | strength {p['strength']} | "
              f"PMID {p['pmid']} | {p['licence']}")
    return params, scores


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify the stored files, no network")
    args = ap.parse_args()
    check() if args.check else build()
