#!/usr/bin/env python3

# =============================================================================
# post_analysis.py
# =============================================================================
#
# DESCRIPTION:
#   Merges the annotated MAF (Mutation Annotation Format) files of a run into a
#   single unified output table. The script produces three output files
#   targeting different audiences and use cases.
#
#   OUTPUT FILES:
#
#     - Final_result_tier1.maf
#         A standard MAF file containing all fields except those marked as
#         "drop" in the YAML config. No metadata second header row. Intended
#         as a clean, tool-compatible MAF file for downstream analysis.
#
#     - Final_result_tier2.tsv
#         A tab-separated file for bioinformaticians. Contains every field whose
#         tier in Config.yaml is 2 *or* 3 — it is a superset of the Tier 3 sheet.
#         Includes a two-row header: field names on row 1, metadata
#         (description, source, version) on row 2.
#
#     - Final_result_tier3.tsv
#         A tab-separated file for clinical scientists. Contains the fields whose
#         tier in Config.yaml is 3. Includes a two-row header: field names on
#         row 1, metadata on row 2. To change which fields appear here, update
#         TIER3_FIELDS in create_config/update_confg.py and re-run it to
#         regenerate Config.yaml.
#
#   Fields marked as "drop" in the YAML config are treated as redundant or
#   duplicate fields and are excluded from ALL output files without exception.
#
# INPUT:
#   - ./FINAL_Table/*.maf — the annotated MAF files of the run. The directory is
#     not an argument; it is relative to the working directory (see USAGE).
#   - A YAML configuration file (Config.yaml) generated by
#     create_config/update_confg.py — the typo in that filename is real, there is
#     no build_config.py — which defines per-field metadata (description, source,
#     version, tier) and wildcard patterns for dynamically generated field groups
#     such as ONCOKB_DIAG_* and ONCOKB_TX_*. The patterns are stored as patterns:
#     they are matched against the run's real column names here, by fnmatch, at
#     run time (resolve_field_meta).
#
# OUTPUT (written to ./output/):
#   - Final_result_tier1.maf   : all non-drop fields, single header, MAF format
#   - Final_result_tier2.tsv   : Tier 2 + Tier 3 fields, two-row header
#   - Final_result_tier3.tsv   : Tier 3 fields, two-row header
#
# PROCESSING STEPS:
#   1.  Standardize FORMAT_DATA column name across all input files
#   2.  Expand FORMAT genotype fields (GT, AD, VAF, etc.) into separate columns
#   3.  Expand structured annotation columns (e.g. CIViC_CSQ) using pipe-
#       delimited subfield definitions from the YAML config
#   4.  Calculate End_Position based on variant type (SNV, indel, SV)
#   5.  Clean field values (replace empty arrays, URL-encoded characters, etc.)
#   6.  Compute VAF from allelic depth (AD) if not already present
#   7.  Add SPLICEAI_MAX_DS and ANNOTATION_FLAGS, so that rows a consequence- or
#       impact-based filter would drop can be kept on their evidence
#   8.  Drop any columns listed in COLS_TO_REMOVE
#   9.  Report columns not documented in the YAML config (warnings only)
#   10. Remove all columns marked as "drop" in the YAML config
#   11. Write Tier 1 MAF file (single header, all remaining columns)
#   12. Split columns by tier (read from Config.yaml) and build two-row headers
#   13. Write Tier 2 and Tier 3 TSV files
#
# TIER DEFINITIONS (assigned by create_config/update_confg.py, not this script):
#   tier 3 : the clinician fields — written to BOTH Final_result_tier3.tsv and
#            Final_result_tier2.tsv
#   tier 2 : the bioinformatician-only fields — Final_result_tier2.tsv only
#   drop   : excluded from every output file
#   anything else, tier 1 included : reaches Final_result_tier1.maf only, and
#            NEITHER TSV. Giving a clinical field tier 1 keeps it out of the
#            clinical sheet; tier 3 is what puts it there.
#
#   Config.yaml names 273 tier-2 and 92 tier-3 fields. A run writes as many
#   columns as it actually produces, which is more, because the ONCOKB_TX_* and
#   ONCOKB_DIAG_* patterns resolve to one column per indexed entry present in the
#   data: the verification1 cohort yields 700 Tier 2 and 78 Tier 3 columns.
#
#   To change tier assignments, edit TIER2_FIELDS, TIER3_FIELDS, or DROP_FIELDS
#   in create_config/update_confg.py and re-run it to regenerate Config.yaml.
#
# USAGE:
#   python3 post_analysis.py --config /data/Config.yaml \
#       [--smart-version 2.1.0] [--vcf-metadata logs] \
#       [--oncokb-version <release>] [--liftover]
#
#   The input and output directories are NOT configurable: the script reads
#   ./FINAL_Table/ and writes ./output/, both relative to the working directory,
#   so it must be run from the run's output base directory. entrypoint.sh cds
#   there before invoking it.
#
#   --vcf-metadata takes the sidecar written by scripts/vcf_metadata.py, or a
#   directory of per-sample sidecars to merge; without it the two-row header is
#   described from Config.yaml alone.
#
# DEPENDENCIES:
#   - Python 3.8+
#   - pandas
#   - pyyaml
#
# RELATED FILES:
#   - create_config/ConfigORIGINAL.yaml : human-maintained field metadata template
#   - Config.yaml                       : generated config consumed by this script,
#                                         passed in with --config
#   - create_config/update_confg.py     : script that generates Config.yaml from
#                                         the template
#   - scripts/vcf_metadata.py           : harvests each run's own field provenance
#
# AUTHOR:
#   Variant annotation pipeline — Manuel
# =============================================================================

