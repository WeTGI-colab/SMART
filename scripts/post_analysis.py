# === Load YAML config ===
def load_field_config(yaml_path):
    """
    Load field metadata and pattern definitions from a YAML configuration file.

    Reads the Config.yaml file generated by build_config.py and extracts:
      - Explicit field definitions (description, source, version, tier)
      - Pattern-based field definitions for dynamically generated columns

    Parameters
    ----------
    yaml_path : str
        Path to the YAML configuration file.

    Returns
    -------
    tuple
        (fields, patterns) where:
        - fields: dict of field metadata
        - patterns: list of wildcard pattern definitions

    Raises
    ------
    ValueError
        If the YAML file does not contain a 'fields' section.
    """

    with open(yaml_path, "r", encoding="utf-8") as f:
        config = yaml.safe_load(f)

    if not config or "fields" not in config:
        raise ValueError(f"YAML file '{yaml_path}' does not contain a top-level 'fields' section.")

    fields = config["fields"]
    patterns = config.get("field_patterns", [])

    return fields, patterns


# Metadata harvested from this run's VCFs, loaded once by load_vcf_metadata(). A VCF describes
# its own fields, and does so for the run that produced them, so it is preferred over Config.yaml
# for everything it covers; Config.yaml keeps the MAF standard columns, the values SMART computes
# and the OncoKB MafAnnotator output, which is a table and has no header to read.
VCF_META = None
RUN_ONCOKB_VERSION = None
LIFTOVER_RAN = False


def load_vcf_metadata(path, oncokb_version=None):
    """Load a sidecar, or merge every sidecar in a directory. Absent is not an error: without
    one the pipeline behaves exactly as it did before, describing fields from Config.yaml."""
    global VCF_META, RUN_ONCOKB_VERSION
    RUN_ONCOKB_VERSION = oncokb_version
    if not path:
        return None
    paths = sorted(glob.glob(os.path.join(path, "*.vcf_metadata.json"))) \
        if os.path.isdir(path) else [path]
    paths = [p for p in paths if os.path.exists(p)]
    if not paths:
        print(f"WARNING: no VCF metadata found at {path}; field provenance falls back to the config")
        return None
    VCF_META = vcf_metadata.merge(paths) if len(paths) > 1 else json.load(open(paths[0]))
    print(f"VCF metadata: {len(VCF_META.get('fields', {}))} field(s) described by the run's own "
          f"VCFs, from {len(paths)} sample sidecar(s)")
    for key in ("input_caller", "vep_version", "vep_cache", "oncokb_data_version"):
        if VCF_META.get("run", {}).get(key):
            print(f"  {key}: {VCF_META['run'][key]}")
    return VCF_META


def report_vcf_metadata_checks(df=None, liftover=False, oncokb_versions=None,
                               field_config=None):
    """Print what the harvest found wrong. Errors mean a value in the output is wrong."""
    if not VCF_META:
        return []
    problems = vcf_metadata.check(VCF_META,
                                 table_columns=list(df.columns) if df is not None else None,
                                 liftover=liftover, oncokb_versions=oncokb_versions)
    if field_config:
        for name, claimed, actual in vcf_metadata.conflicts(VCF_META, field_config):
            problems.append(("warning", f"Config.yaml describes {name} as coming from "
                                        f"'{claimed}', the VCF says '{actual}'. The VCF is used."))
    for level, msg in problems:
        print(f"{level.upper()}: {msg}")
    return problems


# === Resolve field metadata with pattern fallback ===
def resolve_field_meta(col, field_config, field_patterns):
    """
    Resolve metadata for a given column using exact match or pattern matching.

    Attempts to retrieve metadata (description, source, version, tier) for a column:
      1. First checks for an exact match in the field configuration
      2. Falls back to wildcard pattern matching if no exact match is found

    Parameters
    ----------
    col : str
        Column name.
    field_config : dict
        Dictionary of explicitly defined fields.
    field_patterns : list
        List of pattern-based field definitions.

    Returns
    -------
    dict
        Metadata dictionary for the column, or empty dict if not found.
    """

    # A field the run's own VCFs describe is described by them: the file cannot go stale,
    # and it records the resource version actually used.
    if VCF_META:
        return vcf_metadata.resolve(col, VCF_META, field_config, field_patterns,
                                    RUN_ONCOKB_VERSION)

    # Try exact match first
    if col in field_config:
        return field_config[col]

    # Fall back to wildcard pattern matching
    for pattern_def in field_patterns:
        pattern = pattern_def.get("pattern", "")
        if fnmatch.fnmatch(col, pattern):
            return {k: v for k, v in pattern_def.items() if k != "pattern"}

    return {}


# === Step 1: Standardize FORMAT_DATA column per file ===
def standardize_format_column(df):
    """
    Standardize FORMAT sample column naming across input MAF files.

    Renames the column immediately following the 'FORMAT' column to 'FORMAT_DATA'
    to ensure consistency across different input files.

    Parameters
    ----------
    df : pandas.DataFrame
        Input dataframe.

    Returns
    -------
    pandas.DataFrame
        Dataframe with standardized FORMAT_DATA column.
    """

    if "FORMAT" not in df.columns:
        return df

    format_idx = df.columns.get_loc("FORMAT")

    if format_idx + 1 < len(df.columns):
        sample_col = df.columns[format_idx + 1]
        df = df.rename(columns={sample_col: "FORMAT_DATA"})

    return df


# === Step 2: Expand FORMAT fields ===
def normalize_format_fields(df):
    """
    Expand FORMAT genotype fields into individual columns.

    Parses the 'FORMAT' and 'FORMAT_DATA' columns and splits genotype values
    (e.g. GT, AD, VAF) into separate columns for easier downstream analysis.

    Parameters
    ----------
    df : pandas.DataFrame
        Input dataframe.

    Returns
    -------
    pandas.DataFrame
        Dataframe with expanded genotype fields.
    """

    if "FORMAT" not in df.columns or "FORMAT_DATA" not in df.columns:
        return df

    def parse_format(row):

        format_str = str(row.get("FORMAT", "") or "")
        data_str = str(row.get("FORMAT_DATA", "") or "")

        keys = format_str.split(":")
        values = data_str.split(":")

        if len(values) < len(keys):
            values += [None] * (len(keys) - len(values))

        return dict(zip(keys, values))

    parsed_rows = df.apply(parse_format, axis=1)

    all_keys = set()

    for d in parsed_rows:
        all_keys.update(d.keys())

    for key in sorted(all_keys):

        if key in df.columns:
            continue

        df[key] = parsed_rows.apply(lambda d: d.get(key, None))

    return df


# === Step 2.5: Expand structured annotation columns (e.g CIViC_CSQ) ===
def expand_structured_columns(df, field_config):
    """
    Expand structured annotation fields into multiple columns.

    Splits annotation fields (e.g. CIViC_CSQ) into subfields based on the
    pipe-delimited description defined in the YAML configuration.

    Handles both:
      - VEP-style annotations (comma-separated records)
      - CIViC-style annotations (ampersand-separated records)

    Parameters
    ----------
    df : pandas.DataFrame
        Input dataframe.
    field_config : dict
        Field metadata configuration.

    Returns
    -------
    pandas.DataFrame
        Dataframe with expanded annotation columns.
    """

    for field, meta in field_config.items():

        if field not in df.columns:
            continue

        # Only expand fields explicitly marked as pipe-delimited structured fields.
        # Using an explicit opt-in avoids misidentifying natural-language descriptions
        # that happen to contain '|' (e.g. ClinVar_GENEINFO, ClinVar_MC).
        if not meta.get("expand", False):
            continue

        description = meta.get("description", "")

        if "|" not in description:
            continue

        subfields = [x.strip() for x in description.split("|")]
        n_fields = len(subfields)
        def split_first_record(value):

            if pd.isna(value):
                return [None] * n_fields

            value = str(value)

            # CASE 1 — VEP style (records separated by comma)
            if "," in value:
                first_record = value.split(",")[0]
                parts = first_record.split("&")

            # CASE 2 — CIViC style (records concatenated with &)
            else:
                parts_all = value.split("&")

                if len(parts_all) % n_fields != 0:
                    print("WARNING: CIViC field structure mismatch detected in dataset")

                records = [
                    parts_all[i:i+n_fields]
                    for i in range(0, len(parts_all), n_fields)
                ]

                parts = records[0]

            if len(parts) < n_fields:
                parts += [None] * (n_fields - len(parts))

            parts = parts[:n_fields]
            return parts

        expanded = df[field].apply(split_first_record).apply(pd.Series)

        expanded.columns = [f"{field}_{c}" for c in subfields]

        df = df.drop(columns=[field])
        df = pd.concat([df, expanded], axis=1)

    return df


# === Step 2.6: Expand OncoKB JSON array columns ===
# ONCOKB_treatments        → ONCOKB_TX_{index}_{field}
# ONCOKB_diagnosticImpl... → ONCOKB_DIAG_{index}_{field}
# ONCOKB_prognosticImpl... → ONCOKB_PROG_{index}_{field}

_ONCOKB_JSON_FIELDS = {
    "ONCOKB_treatments":              "ONCOKB_TX",
    "ONCOKB_diagnosticImplications":  "ONCOKB_DIAG",
    "ONCOKB_prognosticImplications":  "ONCOKB_PROG",
}


def _flatten_entry(entry, prefix=""):
    """Recursively flatten a dict to dotted key names, serialising lists."""
    out = {}
    for k, v in entry.items():
        full_key = f"{prefix}.{k}" if prefix else k
        if isinstance(v, dict):
            out.update(_flatten_entry(v, full_key))
        elif isinstance(v, list):
            # Lists of dicts (e.g. drugs): join their primary string value
            parts = []
            for item in v:
                if isinstance(item, dict):
                    # prefer drugName, then name, then first value
                    parts.append(str(item.get("drugName") or item.get("name") or next(iter(item.values()), "")))
                else:
                    parts.append(str(item))
            out[full_key] = ",".join(parts)
        else:
            out[full_key] = "" if v is None else str(v)
    return out


def expand_oncokb_json_arrays(df):
    """
    Expand ONCOKB JSON array columns into per-entry flat columns.

    For each row, parses the JSON array and emits columns named
    {PREFIX}_{index}_{field} — e.g. ONCOKB_TX_0_level, ONCOKB_TX_0_drugs.
    The number of index columns is determined by the maximum array length
    across all rows in the dataframe.
    """
    for src_col, col_prefix in _ONCOKB_JSON_FIELDS.items():
        if src_col not in df.columns:
            continue

        # --- Parse each row's JSON array ---
        parsed = []
        max_entries = 0
        for val in df[src_col]:
            try:
                entries = json.loads(val) if val and val != "[]" else []
            except (json.JSONDecodeError, TypeError):
                entries = []
            parsed.append(entries)
            max_entries = max(max_entries, len(entries))

        if max_entries == 0:
            print(f"  {src_col}: all rows empty — skipping expansion")
            continue

        print(f"  {src_col}: expanding {max_entries} entries → prefix {col_prefix}")

        # --- Collect all field names across all entries ---
        all_fields = []
        seen = set()
        for row_entries in parsed:
            for entry in row_entries:
                for k in _flatten_entry(entry).keys():
                    if k not in seen:
                        all_fields.append(k)
                        seen.add(k)

        # --- Build new columns ---
        new_cols = {}
        for i in range(max_entries):
            for field in all_fields:
                col_name = f"{col_prefix}_{i}_{field}"
                new_cols[col_name] = []

        for row_entries in parsed:
            for i in range(max_entries):
                if i < len(row_entries):
                    flat = _flatten_entry(row_entries[i])
                else:
                    flat = {}
                for field in all_fields:
                    col_name = f"{col_prefix}_{i}_{field}"
                    new_cols[col_name].append(flat.get(field, ""))

        new_df = pd.DataFrame(new_cols, index=df.index)
        df = df.drop(columns=[src_col])
        df = pd.concat([df, new_df], axis=1)

    return df


# === Step 3: Calculate End_Position ===
def calculate_end_position(df):
    """
    Compute End_Position for variants based on variant type.

    Determines the genomic end position using:
      - REF/ALT length for SNVs and indels
      - Structural variant annotations (Manta INS, DUP, BND)

    Parameters
    ----------
    df : pandas.DataFrame
        Input dataframe.

    Returns
    -------
    pandas.DataFrame
        Dataframe with 'End_Position' column added.
    """

    def compute_end(row):

        id_val = row.get("ID", "")
        ref = row.get("REF", "") or ""
        alt = row.get("ALT", "") or ""
        dupsvlen = row.get("DUPSVLEN", "")

        try:
            start = int(row["Start_Position"])
        except (ValueError, TypeError, KeyError):
            return None

        if id_val == ".":
            if len(ref) == len(alt):
                return start
            return start + max(len(ref), len(alt)) - 1

        if str(id_val).startswith("MantaBND"):
            return None

        if str(id_val).startswith("MantaINS"):
            if alt == "<INS>":
                try:
                    return start + int(dupsvlen)
                except (ValueError, TypeError):
                    return None
            return start + len(alt)

        if str(id_val).startswith("MantaDUP"):
            try:
                return start + int(dupsvlen)
            except (ValueError, TypeError):
                return None

        return None

    df["End_Position"] = df.apply(compute_end, axis=1)

    return df


# === Step 4: Clean values ===
def clean_column_values(df):
    """
    Clean and normalize column values.

    Performs:
      - Replacement of placeholder values (e.g. '[]', URL-encoded characters)
      - Normalization of HGVSc field (removal of transcript prefix)

    Parameters
    ----------
    df : pandas.DataFrame
        Input dataframe.

    Returns
    -------
    pandas.DataFrame
        Cleaned dataframe.
    """

    df = df.replace({"[]": "", "%3D": "="}, regex=False).infer_objects(copy=False)

    if "HGVSc" in df.columns:
        df["HGVSc"] = (
            df["HGVSc"]
            .astype(str)
            .apply(lambda x: x.split(":", 1)[1] if ":" in x else x)
        )

    return df


# === Step 5: Compute VAF ===
def add_vaf_column(df, ad_column="AD"):
    """
    Compute Variant Allele Frequency (VAF) from allelic depth.

    Calculates VAF using:
        VAF = ALT / (REF + ALT)

    Parameters
    ----------
    df : pandas.DataFrame
        Input dataframe.
    ad_column : str, optional
        Column containing allelic depth (default is 'AD').

    Returns
    -------
    pandas.DataFrame
        Dataframe with 'VAF' column added.
    """

    if ad_column not in df.columns:
        return df

    def compute_vaf(value):

        try:
            ref, alt = str(value).split(",")
            ref = float(ref)
            alt = float(alt)
            total = ref + alt
            return alt / total if total > 0 else 0
        except Exception:
            return None

    df["VAF"] = df[ad_column].apply(compute_vaf)

    return df


# === Step 5b: Annotation flags ===
# github.com/WeTGI-colab/SMART/issues/14 (SpliceAI evidence on LOW/MODIFIER rows)
# github.com/WeTGI-colab/SMART/issues/15 (the TERT promoter hotspot positions)
# Both ask for the same thing: a row a filter would drop must be keepable on its
# evidence. See docs/annotation_flags.md.
SPLICEAI_DS_COLUMNS = ("SpliceAI_pred_DS_AG", "SpliceAI_pred_DS_AL",
                       "SpliceAI_pred_DS_DG", "SpliceAI_pred_DS_DL")

# 0.2 is the delta at which the classifier starts awarding O6. Flagging from the same
# value means every variant that could earn O6 reaches the classifier; a laboratory that
# wants a stricter cut filters on SPLICEAI_MAX_DS itself.
SPLICEAI_FLAG_THRESHOLD = 0.2

# Only LOW and MODIFIER rows are flagged: those are the ones an impact filter removes.
# HIGH and MODERATE survive such a filter anyway, and their scores are in SPLICEAI_MAX_DS
# either way.
SPLICEAI_FLAG_IMPACTS = ("LOW", "MODIFIER")

CANONICAL_VARIANTS_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                       "..", "reference_lists",
                                       "svig_uk_canonical_variants.tsv")


def _max_score(value):
    """The largest number in one SpliceAI cell, or None.

    Equivalent to the classifier's fnum() for the single values SpliceAI actually
    writes; the search is used so that a cell carrying more than one prediction
    cannot silently drop its evidence by failing to parse as one float.
    """
    s = str(value).strip()
    if s in ("", ".", "-", "nan", "NaN", "None", "NA"):
        return None
    found = [float(m) for m in re.findall(r"-?\d+\.?\d*(?:[eE][-+]?\d+)?", s)]
    return max(found) if found else None


def load_canonical_genomic(path=None):
    """Genomic entries of the SVIG-UK canonical list as {(chrom, pos, ref, alt)}.

    Read from the same reference file the classifier uses for O1, so the annotation
    flag and the classification rule cannot drift apart, and so the set extends by
    itself if non-coding entries are added to the list. Entries matched by protein
    change or by a bespoke rule are skipped: a genomic position is what an annotation
    flag can test, and a promoter variant's c. notation depends on the transcript
    annotated while its position does not.
    """
    path = path or CANONICAL_VARIANTS_PATH
    out = set()
    if not os.path.exists(path):
        print(f"WARNING: canonical variant list not found at {path}; "
              f"svig_canonical will not be flagged")
        return out
    with open(path, newline="", encoding="utf-8") as fh:
        for entry in csv.DictReader(fh, delimiter="\t"):
            rule = (entry.get("match_rule") or "").strip()
            if not rule.startswith("genomic:"):
                continue
            parts = rule.split(":")
            if len(parts) != 5:
                print(f"WARNING: malformed genomic match_rule {rule!r}; skipped")
                continue
            _, chrom, pos, ref, alt = parts
            out.add((chrom.replace("chr", ""), str(pos), ref, alt))
    return out


def add_annotation_flags(df, canonical=None):
    """Add SPLICEAI_MAX_DS and ANNOTATION_FLAGS.

    ANNOTATION_FLAGS states why a row is worth keeping when a consequence- or
    impact-based filter would otherwise drop it, ';'-separated:

      splice_predicted(0.95)  a LOW/MODIFIER row whose maximum SpliceAI delta
                              reaches SPLICEAI_FLAG_THRESHOLD
      svig_canonical          a position on the SVIG-UK canonical variants list
                              (today the two TERT promoter hotspots)

    Variant_Classification is deliberately left alone. It is a defined MAF vocabulary
    describing the consequence: a splice-predicted synonymous variant is still
    synonymous, rewriting it would break third-party readers of the MAF and would
    destroy the record of what the consequence actually was. The filter changes from
    "drop Silent/Intron" to "drop Silent/Intron unless ANNOTATION_FLAGS is non-empty",
    and one column carries every such reason rather than one column per reason.

    ANNOTATION_FLAGS is always created, empty where nothing is flagged, so the
    consuming filter can rely on the column existing.

    Parameters
    ----------
    df : pandas.DataFrame
        Input dataframe.
    canonical : set, optional
        Genomic keys from load_canonical_genomic(); loaded on demand when omitted.

    Returns
    -------
    pandas.DataFrame
        Dataframe with 'SPLICEAI_MAX_DS' and 'ANNOTATION_FLAGS' added.
    """
    if canonical is None:
        canonical = load_canonical_genomic()

    present = [c for c in SPLICEAI_DS_COLUMNS if c in df.columns]
    if present:
        # float, not object: the column exists to be sorted and compared on, and an
        # object column of floats and Nones sorts as text in some readers
        scores = df[present].apply(
            lambda col: pd.to_numeric(col.map(_max_score), errors="coerce"))
        df["SPLICEAI_MAX_DS"] = scores.max(axis=1, skipna=True)
    else:
        print("WARNING: no SpliceAI delta columns found; SPLICEAI_MAX_DS left empty")
        df["SPLICEAI_MAX_DS"] = float("nan")

    def flags_for(row):
        flags = []
        score = row.get("SPLICEAI_MAX_DS")
        impact = str(row.get("IMPACT", "")).strip().upper()
        if (score is not None and pd.notna(score)
                and score >= SPLICEAI_FLAG_THRESHOLD
                and impact in SPLICEAI_FLAG_IMPACTS):
            flags.append(f"splice_predicted({score:g})")
        key = (str(row.get("Chromosome", "")).replace("chr", ""),
               str(row.get("Start_Position", "")),
               row.get("Reference_Allele"), row.get("Tumor_Seq_Allele2"))
        if key in canonical:
            flags.append("svig_canonical")
        return ";".join(flags)

    df["ANNOTATION_FLAGS"] = df.apply(flags_for, axis=1)

    n = int((df["ANNOTATION_FLAGS"] != "").sum())
    if n:
        print(f"Annotation flags set on {n} row(s)")
    return df


