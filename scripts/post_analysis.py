# === Main merge function ===
def _apply_oncokb_fixes(df):
    """Per-sample OncoKB / CNA fixes (all row-wise within one sample).
    Returns (df, n_highestfda_filled, n_cna_rows)."""
    n_filled = 0
    # Every column this function fills is written as a string into a column read with
    # dtype=str. Where the MAF had that column empty on every row it arrives as float64,
    # and the write would raise on a future pandas. Cast up front, in one place, so a
    # column that is empty for a given cohort is not a latent failure.
    _as_object(df,
               "ONCOKB_highestFdaLevel", "VARIANT_IN_ONCOKB", "GENE_IN_ONCOKB",
               "ONCOGENIC", "MUTATION_EFFECT", "MUTATION_EFFECT_CITATIONS",
               "LEVEL_1", "LEVEL_2", "LEVEL_3A", "LEVEL_3B", "LEVEL_4",
               "LEVEL_R1", "LEVEL_R2",
               "HIGHEST_SENSITIVE_LEVEL", "HIGHEST_RESISTANCE_LEVEL")

    # Fix 1: fill empty ONCOKB_highestFdaLevel from ONCOKB_FDA_LVL
    if "ONCOKB_highestFdaLevel" in df.columns and "ONCOKB_FDA_LVL" in df.columns:
        mask = df["ONCOKB_highestFdaLevel"].map(_is_blank)
        df.loc[mask, "ONCOKB_highestFdaLevel"] = _as_text(df.loc[mask, "ONCOKB_FDA_LVL"])
        n_filled = int(mask.sum())

    # Fix 2: CNA rows — MafAnnotator cannot annotate CNAs; overwrite from the
    # oncokb2.0.py source columns.
    cna_mask = df.get("ONCOKB_QUERY_TYPE", pd.Series("", index=df.index)).map(
        lambda v: "" if _is_blank(v) else str(v)).eq("CNA")
    n_cna = int(cna_mask.sum())
    if cna_mask.any():
        if "VARIANT_IN_ONCOKB" in df.columns and "ONCOKB_variantExist" in df.columns:
            df.loc[cna_mask, "VARIANT_IN_ONCOKB"] = _as_text(df.loc[cna_mask, "ONCOKB_variantExist"])
        # MafAnnotator leaves GENE_IN_ONCOKB False on a CNA row because it cannot annotate
        # CNAs at all, which read as "OncoKB does not know this gene" for ERBB2, MET, CDK4 and
        # CDKN2A. oncokb2.0.py already asked and recorded the answer.
        if "GENE_IN_ONCOKB" in df.columns and "ONCOKB_geneExist" in df.columns:
            df.loc[cna_mask, "GENE_IN_ONCOKB"] = _as_text(df.loc[cna_mask, "ONCOKB_geneExist"])
        if "ONCOGENIC" in df.columns and "ONCOKB_oncogenic" in df.columns:
            df.loc[cna_mask, "ONCOGENIC"] = _as_text(df.loc[cna_mask, "ONCOKB_oncogenic"])
        if "MUTATION_EFFECT" in df.columns and "ONCOKB_mutationEffect.knownEffect" in df.columns:
            df.loc[cna_mask, "MUTATION_EFFECT"] = _as_text(df.loc[cna_mask, "ONCOKB_mutationEffect.knownEffect"])
        if "MUTATION_EFFECT_CITATIONS" in df.columns and "ONCOKB_mutationEffect.citations.pmids" in df.columns:
            def _norm_pmids(v):
                v = str(v).strip()
                if not v or v in ("[]", "nan", ""):
                    return ""
                v = v.strip("[]").replace("'", "").replace('"', "")
                return ";".join(x.strip() for x in v.split(",") if x.strip())
            df.loc[cna_mask, "MUTATION_EFFECT_CITATIONS"] = (
                _as_text(df.loc[cna_mask, "ONCOKB_mutationEffect.citations.pmids"]).map(_norm_pmids)
            )
        # Levels come from the per-entry columns, not from the stringified blob.
        # ONCOKB_TX_{n}_level and ONCOKB_TX_{n}_drugs are written upstream by oncokb2.0.py from
        # the real API response, so they are structured and already populated. Re-parsing
        # ONCOKB_treatments was the original approach and cannot work: its free text carries
        # unescaped apostrophes, which close a Python literal early. Reading the columns needs
        # no parsing at all.
        _tx_levels = [c for c in df.columns
                      if c.startswith("ONCOKB_TX_") and c.endswith("_level")]
        if _tx_levels:
            _level_cols_tx = ["LEVEL_1", "LEVEL_2", "LEVEL_3A", "LEVEL_3B",
                              "LEVEL_4", "LEVEL_R1", "LEVEL_R2"]

            def _levels_from_columns(idx):
                out = {lc: [] for lc in _level_cols_tx}
                for lvl_col in _tx_levels:
                    n = lvl_col[len("ONCOKB_TX_"):-len("_level")]
                    _lv = df.at[idx, lvl_col]
                    lvl = ("" if _lv is None else str(_lv)).strip()
                    if lvl not in out:
                        continue
                    drug_col = f"ONCOKB_TX_{n}_drugs"
                    if drug_col not in df.columns:
                        continue
                    _dr = df.at[idx, drug_col]
                    drugs = ("" if _dr is None else str(_dr)).strip()
                    if drugs in ("", "nan", "NaN", "None", "."):
                        continue
                    # a combination arrives as "A + B"; the verifier and OncoKB list each drug
                    for name in [d.strip() for d in drugs.replace("+", ",").split(",")]:
                        if name and name not in out[lvl]:
                            out[lvl].append(name)
                return {k: ",".join(v) for k, v in out.items()}

            for cna_idx in df.index[cna_mask]:
                for lc, val in _levels_from_columns(cna_idx).items():
                    if lc in df.columns and val and _is_blank(df.at[cna_idx, lc]):
                        df.at[cna_idx, lc] = val

        if "ONCOKB_treatments" in df.columns:
            _level_cols = ["LEVEL_1", "LEVEL_2", "LEVEL_3A", "LEVEL_3B",
                           "LEVEL_4", "LEVEL_R1", "LEVEL_R2"]

            def _extract_levels(treatments_json):
                treatments = []
                # The value reaches us encoded once or twice depending on the path it took:
                # MET and CDKN2A arrive as a Python repr, which literal_eval reads, while CDK4
                # and ERBB2 arrive as that repr wrapped in a JSON string, so one parse yields
                # the inner *string* rather than the list. Iterating that string is what raised
                # AttributeError, and stopping at it silently would lose every treatment level
                # for those rows. So parse until a list appears, with a bound so a pathological
                # value cannot spin.
                if treatments_json and treatments_json not in ("[]", "", "nan"):
                    # Newlines are normalised because OncoKB's free text carries real ones --
                    # 39 lines for ERBB2 amplification -- and a single-quoted Python literal
                    # cannot span lines. Necessary but NOT sufficient: the same free text also
                    # contains unescaped apostrophes, which close a literal early and leave the
                    # rest unbalanced, so this value cannot be parsed at all for some rows and
                    # their per-level drug columns stay empty. Parsing a stringified structure
                    # downstream is the wrong design; the fix belongs in oncokb2.0.py, which
                    # holds the real JSON from the API. See the open issue on CNA levels.
                    candidate = str(treatments_json).replace("\r", " ").replace("\n", " ")
                    for _ in range(3):
                        parsed = None
                        try:
                            parsed = json.loads(candidate)
                        except (json.JSONDecodeError, TypeError):
                            try:
                                parsed = ast.literal_eval(candidate)
                            except Exception:
                                break
                        if isinstance(parsed, str):
                            candidate = parsed      # it was encoded again; go round
                            continue
                        treatments = parsed
                        break
                # Both parsers can succeed and still not return what this expects: a quoted
                # string parses to a str, and iterating a str yields characters, so t.get()
                # raised AttributeError on a CNA row whose treatments had already been
                # flattened to drug names. Validate the shape rather than trust the parse.
                if not isinstance(treatments, list):
                    treatments = []
                out = {lc: [] for lc in _level_cols}
                for t in treatments:
                    if not isinstance(t, dict):
                        continue
                    lvl = t.get("level", "")
                    if lvl in out:
                        drugs = t.get("drugs", [])
                        for d in (drugs if isinstance(drugs, list) else []):
                            name = d.get("drugName", "") if isinstance(d, dict) else ""
                            if name and name not in out[lvl]:
                                out[lvl].append(name)
                return {k: ",".join(v) for k, v in out.items()}

            # Fallback only. The structured ONCOKB_TX_{n}_level / _drugs columns above are
            # written by oncokb2.0.py from the API response and are the reliable source;
            # this parses the stringified blob, which fails for any row whose free text
            # carries an apostrophe. It runs second, so without the blank test it would
            # overwrite a correct value with whatever the blob happened to yield.
            for cna_idx in df.index[cna_mask]:
                levels = _extract_levels(df.at[cna_idx, "ONCOKB_treatments"])
                for lc, val in levels.items():
                    if lc in df.columns and val and _is_blank(df.at[cna_idx, lc]):
                        df.at[cna_idx, lc] = val
        if "HIGHEST_SENSITIVE_LEVEL" in df.columns and "ONCOKB_SENS_LVL" in df.columns:
            hs_empty = cna_mask & df["HIGHEST_SENSITIVE_LEVEL"].map(_is_blank)
            df.loc[hs_empty, "HIGHEST_SENSITIVE_LEVEL"] = _as_text(df.loc[hs_empty, "ONCOKB_SENS_LVL"])
        if "HIGHEST_RESISTANCE_LEVEL" in df.columns and "ONCOKB_RESIST_LVL" in df.columns:
            hr_empty = cna_mask & df["HIGHEST_RESISTANCE_LEVEL"].map(_is_blank)
            df.loc[hr_empty, "HIGHEST_RESISTANCE_LEVEL"] = _as_text(df.loc[hr_empty, "ONCOKB_RESIST_LVL"])
    return df, n_filled, n_cna


def strip_embedded_whitespace(df):
    """Replace embedded newlines / carriage returns / tabs with a single space in
    every cell.

    A MAF/TSV is one record per physical line, tab-delimited. OncoKB free-text
    fields (citation abstracts, mutation-effect descriptions) can contain literal
    newlines or tabs; if written verbatim they split a record into a phantom row
    with a blank Tumor_Sample_Barcode and every column shifted, which corrupts the
    MAF. Collapsing these characters to a space keeps each record on one clean line.

    Substituted cell by cell on the values that are actually strings, rather than with
    `DataFrame.replace(regex=True)` over the frame. Nothing numeric can hold a newline, so
    the result is identical, but `replace` also re-infers dtypes: it silently downcast the
    all-NaN object and float columns that a dtype=str read produces, which pandas has
    deprecated and will remove, so the vectorised form was going to start failing. Testing
    isinstance keeps NaN as NaN instead of turning it into the string "nan".
    """
    out = df.copy()
    for c in out.columns:
        if out[c].dtype == object:
            out[c] = out[c].map(
                lambda v: _EMBEDDED_WS_RE.sub(" ", v) if isinstance(v, str) else v)
    return out


def _transform_sample(df, field_config):
    """All per-row transformations for a single sample's MAF (no cross-sample state)."""
    df = standardize_format_column(df)
    df = calculate_end_position(df)
    df = normalize_format_fields(df)
    df = expand_structured_columns(df, field_config)
    df = expand_oncokb_json_arrays(df)
    df = clean_column_values(df)
    df = add_vaf_column(df)
    df = add_annotation_flags(df)
    df, n_filled, n_cna = _apply_oncokb_fixes(df)
    df = drop_columns(df, COLS_TO_REMOVE)
    df = strip_embedded_whitespace(df)   # guard: no \n / \t / \r in any cell -> one clean MAF row per record
    return df, n_filled, n_cna


def merge_maf_files(input_dir, output_dir, yaml_config, smart_version="unknown",
                    liftover=False):
    """Merge per-sample MAFs into the three tiered outputs with a streaming,
    two-pass strategy: peak memory stays at ~one sample regardless of cohort size.

    Pass 1 transforms each sample independently, caches it to a temp pickle, and
    accumulates the global ordered union of column names. Pass 2 streams each
    cached sample, aligns it to that schema, and appends its rows to the outputs.
    """
    field_config, field_patterns = load_field_config(yaml_config)

    maf_files = sorted(f for f in os.listdir(input_dir) if f.lower().endswith(".maf"))
    if not maf_files:
        raise ValueError("No MAF files found in the directory.")

    os.makedirs(output_dir, exist_ok=True)
    tmp_dir = tempfile.mkdtemp(prefix="smart_merge_")

    try:
        # ---- PASS 1: per-sample transform + cache; accumulate column union ----
        global_cols, seen, tmp_files = [], set(), []
        total_filled = total_cna = total_rows = 0
        for i, maf in enumerate(maf_files):
            path = os.path.join(input_dir, maf)
            print(f"[pass 1] transforming: {path}")
            df = pd.read_csv(path, sep="\t", dtype=str)
            df, nf, nc = _transform_sample(df, field_config)
            total_filled += nf
            total_cna += nc
            total_rows += len(df)
            for c in df.columns:
                if c not in seen:
                    seen.add(c)
                    global_cols.append(c)
            tmp = os.path.join(tmp_dir, f"part_{i:06d}.pkl")
            df.to_pickle(tmp)
            tmp_files.append(tmp)
            del df

        if total_filled:
            print(f"\nFilled {total_filled} empty ONCOKB_highestFdaLevel values from ONCOKB_FDA_LVL")
        if total_cna:
            print(f"Applied CNA overwrite fix for {total_cna} CNA rows "
                  "(VARIANT_IN_ONCOKB, ONCOGENIC, MUTATION_EFFECT, treatment levels, highest levels)")

        report_undocumented_columns(pd.DataFrame(columns=global_cols), field_config, field_patterns)

        # ---- Resolve final column sets from the global union (by name) ----
        n_drop = 0
        final_cols, tier2_cols, tier3_cols = [], [], []
        for col in global_cols:
            tier = resolve_field_meta(col, field_config, field_patterns).get("tier")
            if tier == "drop":
                n_drop += 1
                continue
            final_cols.append(col)
            if tier == 2:
                tier2_cols.append(col)
            elif tier == 3:
                tier3_cols.append(col)
                tier2_cols.append(col)

        print(f"\nDropped columns (tier=drop): {n_drop}")
        print(f"Tier1 columns: {len(final_cols)}")
        print(f"Tier2 columns: {len(tier2_cols)}")
        print(f"Tier3 columns: {len(tier3_cols)}")
        print(f"Total rows across {len(maf_files)} sample(s): {total_rows}")

        def _meta_row(cols):
            row = []
            for col in cols:
                m = resolve_field_meta(col, field_config, field_patterns)
                row.append(f"{m.get('description', 'UNKNOWN')} | "
                           f"{m.get('source', 'UNKNOWN')} | {m.get('version', 'UNKNOWN')}")
            return row

        tier1_maf  = os.path.join(output_dir, "Final_result_tier1.maf")
        tier2_file = os.path.join(output_dir, "Final_result_tier2.tsv")
        tier3_file = os.path.join(output_dir, "Final_result_tier3.tsv")
        write_t3 = len(tier3_cols) > 0

        # ---- PASS 2: stream each cached sample, align to schema, append ----
        print(f"\nWriting tiered outputs (streaming): {output_dir}")
        with open(tier1_maf, "w") as f1, open(tier2_file, "w") as f2, \
                (open(tier3_file, "w") if write_t3 else nullcontext()) as f3:

            f1.write(f"#SMART_VERSION {smart_version}\n")
            pd.DataFrame(columns=final_cols).to_csv(f1, sep="\t", index=False)
            pd.DataFrame([_meta_row(tier2_cols)], columns=tier2_cols).to_csv(f2, sep="\t", index=False)
            if write_t3:
                pd.DataFrame([_meta_row(tier3_cols)], columns=tier3_cols).to_csv(f3, sep="\t", index=False)

            for tmp in tmp_files:
                df = pd.read_pickle(tmp).reindex(columns=final_cols, fill_value="")
                df.to_csv(f1, sep="\t", index=False, header=False)
                df[tier2_cols].to_csv(f2, sep="\t", index=False, header=False)
                if write_t3:
                    df[tier3_cols].to_csv(f3, sep="\t", index=False, header=False)
                del df

        if not write_t3:
            print("\nWARNING: No Tier 3 columns found in data.")
            print("To populate Final_result_tier3.tsv, add tier-3 fields to Config.yaml.")
    finally:
        shutil.rmtree(tmp_dir, ignore_errors=True)


