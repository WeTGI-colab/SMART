"""docs/fields.md must still describe the configuration it claims to describe.

`docs/fields.md` is published at /SMART/fields/ and linked from the README as the "Full
field reference". It is what a reporting scientist opens to find out what an output column
means, and it was maintained by hand. The hand lost:

  * **354 columns against Config.yaml's 427.** Missing: every dbNSFP predictor (49
    columns), every COSMIC CMC column, all ten `GENIE_*` columns, both CADD columns,
    `ANNOTATION_FLAGS`, `SPLICEAI_MAX_DS`, `TRANSCRIPT_MATCH`, `TRANSCRIPT_REQUESTED` and
    `ONCOKB_MAF_QUERY` — 73 entries, a sixth of the configuration, including the columns
    the SVIG-UK classifier reads.
  * **Ten names that matched nothing.** `ONCOKB_PROG_*_levelOfEvidence` and nine siblings
    were listed as though documented; Config.yaml has no such entry and no such pattern,
    so a reader could look up a column the pipeline cannot describe.
  * **A correction that landed in Config.yaml and not here.** `LOEUF`'s source was still a
    bare Karczewski 2020 citation, which the root Config.yaml had already replaced because
    those values do not come from that paper.

So the page is generated by `utils/gen_fields_doc.py`, and these tests are the part that
keeps it generated: the page on disk must be byte-identical to what the generator writes
from today's Config.yaml. Edit Config.yaml without regenerating and
`test_the_page_on_disk_is_what_the_generator_writes` fails and says so.

The checks are aggregate rather than parametrised per column: 427 parametrised cases would
quadruple this suite's test count, which `test_documented_numbers.py` compares against the
READMEs.
"""

import fnmatch
import html
import importlib.util
import os
import re
import subprocess
import sys

import pytest
import yaml

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
CONFIG = os.path.join(ROOT, "Config.yaml")
PAGE = os.path.join(ROOT, "docs", "fields.md")
GENERATOR = os.path.join(ROOT, "utils", "gen_fields_doc.py")

# One row of the page: the column name is in data-field, the five cells follow.
ROW_RE = re.compile(r'<tr data-field="(?P<name>[^"]*)"[^>]*>(?P<cells>.*?)</tr>', re.S)
PATTERN_ROW_RE = re.compile(r'<tr data-pattern="(?P<pattern>[^"]*)"[^>]*>(?P<cells>.*?)</tr>',
                            re.S)
CELL_RE = re.compile(r"<td[^>]*>(.*?)</td>", re.S)
BADGE_RE = re.compile(r'<span class="badge [^"]*">([^<]*)</span>')


def _load_generator():
    """utils/ is not a package, so the generator is loaded by path, as conftest does."""
    spec = importlib.util.spec_from_file_location("gen_fields_doc", GENERATOR)
    mod = importlib.util.module_from_spec(spec)
    sys.modules["gen_fields_doc"] = mod
    spec.loader.exec_module(mod)
    return mod


gen = _load_generator()


@pytest.fixture(scope="module")
def page():
    with open(PAGE, encoding="utf-8") as fh:
        return fh.read()


@pytest.fixture(scope="module")
def config():
    with open(CONFIG, encoding="utf-8") as fh:
        return yaml.safe_load(fh)


@pytest.fixture(scope="module")
def entries(config):
    return gen.entries(config)


@pytest.fixture(scope="module")
def patterns(config):
    """The distinct patterns. Config.yaml lists 37 entries, two of them identical."""
    return gen.patterns(config)


def flat(value):
    """A string with its whitespace collapsed.

    Ten Config.yaml entries (the SpliceAI block) keep newlines in their YAML descriptions.
    The generator collapses them, because an embedded newline would split a table row
    across lines and a blank line would end the HTML block in Markdown, so the comparison
    collapses them too.
    """
    return " ".join(str("" if value is None else value).split())


def text(cell):
    """One table cell as the plain text a reader sees."""
    return flat(html.unescape(re.sub(r"<[^>]+>", "", cell)))


def rows(page):
    """{column name: [description, source, version, tier]} as the page states them."""
    out = {}
    for m in ROW_RE.finditer(page):
        cells = CELL_RE.findall(m.group("cells"))
        out[html.unescape(m.group("name"))] = [text(c) for c in cells[1:]]
    return out


def pattern_rows(page):
    return {html.unescape(m.group("pattern")): [text(c) for c in CELL_RE.findall(m.group("cells"))[1:]]
            for m in PATTERN_ROW_RE.finditer(page)}


class TestEveryConfiguredColumnIsOnThePage:
    """The 73-entry hole, and the shape of hole it was."""

    def test_every_column_entry_appears(self, page, entries):
        missing = sorted(set(entries) - set(rows(page)))
        assert not missing, (
            f"{len(missing)} of {len(entries)} Config.yaml columns are absent from "
            f"docs/fields.md: {missing[:15]}. Regenerate with "
            f"`python3 utils/gen_fields_doc.py`.")

    def test_the_page_names_no_column_the_configuration_lacks(self, page, entries, patterns):
        """The page must not offer a lookup the pipeline cannot honour.

        The hand-written version listed ten `ONCOKB_PROG_*_…` names. post_analysis.py does
        expand that OncoKB array into columns, but Config.yaml describes none of them, so
        the page was promising a description that no run can print.
        """
        known = [p.get("pattern", "") for p in patterns]
        invented = sorted(name for name in rows(page)
                          if name not in entries
                          and not any(fnmatch.fnmatch(name, k) for k in known))
        assert not invented, (
            f"docs/fields.md documents {len(invented)} name(s) that Config.yaml neither "
            f"lists nor matches by pattern: {invented[:15]}")

    def test_the_counts_agree(self, page, entries, patterns):
        """A count is the cheapest way to notice drift, and it was 354 against 427."""
        assert len(rows(page)) == len(entries), (
            f"docs/fields.md has {len(rows(page))} column rows against Config.yaml's "
            f"{len(entries)} entries")
        assert len(pattern_rows(page)) == len(patterns), (
            f"docs/fields.md has {len(pattern_rows(page))} pattern rows against "
            f"Config.yaml's {len(patterns)} distinct patterns")
        assert f"{len(entries)} column entries" in page, (
            "the generated-file banner no longer states the column count it was built from")

    def test_every_description_source_version_and_tier_matches(self, page, entries):
        """Presence is not currency.

        `LOEUF` was present throughout, attributed to a paper the root Config.yaml had
        already stopped citing. Comparing the text, not just the name, is what catches a
        correction that was made in the configuration and never propagated here.
        """
        stated = rows(page)
        drift = []
        for name, meta in entries.items():
            if name not in stated:
                continue
            desc, source, version, tier = stated[name]
            want_version = flat(meta.get("version", "") or "")
            want_tier = "drop" if meta.get("tier") == "drop" else str(meta.get("tier"))
            for label, want, got in (
                    ("description", flat(meta.get("description", "")), desc),
                    ("source", flat(meta.get("source", "")), source),
                    ("version", want_version or "n/a", version),
                    ("tier", want_tier, tier)):
                if want != got:
                    drift.append(f"{name}.{label}:\n      config: {want[:120]}\n"
                                 f"      page:   {got[:120]}")
        assert not drift, (
            f"{len(drift)} statement(s) in docs/fields.md disagree with Config.yaml. The "
            f"configuration is authoritative; regenerate the page.\n    "
            + "\n    ".join(drift[:8]))


class TestThePageIsGeneratedAndStaysGenerated:
    def test_the_page_on_disk_is_what_the_generator_writes(self, page, config):
        """This is the test that fails when Config.yaml is edited and the page is not.

        The generator's output is deterministic -- no timestamps -- so byte identity is a
        fair comparison and the only one that covers prose, counts, grouping and rows at
        once.
        """
        expected = gen.render(config)
        assert page == expected, (
            "docs/fields.md is not what utils/gen_fields_doc.py produces from "
            "Config.yaml. If you changed Config.yaml, regenerate:\n"
            "    python3 utils/gen_fields_doc.py\n"
            "If you edited docs/fields.md by hand, move the change into Config.yaml or "
            "into the generator -- the file is overwritten.")

    def test_the_generator_check_mode_agrees(self):
        """CI and a pre-commit hook need a one-command answer, so --check must work."""
        done = subprocess.run([sys.executable, GENERATOR, "--check"],
                              cwd=ROOT, capture_output=True, text=True)
        assert done.returncode == 0, done.stdout + done.stderr

    def test_the_page_says_it_is_generated_and_by_what(self, page):
        """Nothing stops a hand edit except telling the next person not to make one."""
        assert "GENERATED FILE" in page
        assert "utils/gen_fields_doc.py" in page
        assert "Config.yaml" in page
        assert "python3 utils/gen_fields_doc.py" in page, (
            "the page must name the command that regenerates it")
        assert "tests/verification5/test_fields_doc.py" in page, (
            "the page should name the test that holds it current")


class TestThePageStillExplainsItself:
    """A generated reference that lost its prose would be worse than a stale one."""

    def test_the_jekyll_front_matter_survives(self, page):
        assert page.startswith("---\nlayout: default\n"), (
            "the page is published by Jekyll at the permalink in its front matter")
        assert "permalink: /fields/" in page, (
            "README links https://…github.io/SMART/fields/; changing the permalink breaks it")

    def test_the_introduction_and_example_link_survive(self, page):
        assert "annotations from multiple sources" in page, "the intro prose is gone"
        assert "utation" in page and "eporting" in page, (
            "the expansion of the SMART acronym is gone")
        assert "example-output.html" in page, (
            "the link to the browsable example output was dropped")

    def test_it_says_what_the_tiers_mean(self, page):
        for name in ("Final_result_tier1.maf", "Final_result_tier2.tsv",
                     "Final_result_tier3.tsv"):
            assert name in page, f"the tier section no longer names {name}"

    def test_the_tier_routing_it_describes_is_the_routing_the_code_performs(self, page):
        """The page's tier table is checked against the code, not trusted as prose.

        Prose about routing goes stale: `create_config/README.md` described Tier 1 as
        "primary clinical … shown by default" and Tier 3 as "reserved for future use",
        while post_analysis.py did the opposite — tier 3 appended to both tier3_cols and
        tier2_cols, tier 2 only to tier2_cols, everything else to the MAF alone. A reader
        who believed that table would open the wrong sheet. This page says the same thing
        in prose, so the claim is tied back to the loop that implements it: if the routing
        changes, this fails and the table needs rewriting with it.
        """
        code = open(os.path.join(ROOT, "scripts", "post_analysis.py"), encoding="utf-8").read()
        routing = re.search(
            r'if tier == "drop":.*?elif tier == 3:\s*\n(?P<t3>(?:\s+\w+\.append\(col\)\s*\n)+)',
            code, re.S)
        assert routing, ("the tier routing loop in scripts/post_analysis.py no longer has "
                         "the shape this test reads; re-check docs/fields.md against it")
        appended = re.findall(r"(\w+)\.append\(col\)", routing.group("t3"))
        assert set(appended) == {"tier3_cols", "tier2_cols"}, (
            f"tier 3 now goes to {appended}; the page says it reaches both TSVs")

        table = [line for line in page.splitlines() if line.startswith("| `")]
        routing_rows = {line.split("|")[1].strip().strip("`"): [c.strip() for c in line.split("|")[2:5]]
                        for line in table}
        assert routing_rows.get("3") == ["Yes", "Yes", "Yes"], (
            "the page must say a tier 3 column reaches all three output files")
        assert routing_rows.get("2") == ["&ndash;", "Yes", "Yes"], (
            "a tier 2 column reaches the Tier 2 sheet and the MAF, not the Tier 3 sheet")
        assert routing_rows.get("drop") == ["&ndash;", "&ndash;", "&ndash;"]

    def test_the_patterns_are_shown_as_patterns_not_invented_columns(self, page, patterns):
        """The 37 pattern entries are real documentation but not real column names.

        Omitting them would drop every indexed OncoKB column from the reference; expanding
        them would invent column names whose count depends on the run. They get their own
        section, reproduced verbatim.
        """
        shown = pattern_rows(page)
        missing = sorted({p.get("pattern", "") for p in patterns} - set(shown))
        assert not missing, f"patterns absent from the page: {missing[:10]}"
        assert "fnmatch" in page, "the page should say how a pattern is resolved"
        assert not any("*" in name for name in rows(page)), (
            "a pattern is listed as though it were a concrete column")
        assert "ONCOKB_TX_0_level" not in shown, (
            "patterns must not be expanded into concrete column names")

    def test_the_in_page_filter_can_run(self, page):
        """The published page's search box threw on every keystroke.

        The hand-written version's filterTable() read `tier`, which nothing declared, so
        each call raised a ReferenceError: the search box, the source filter and the
        "N of M fields shown" counter all did nothing, silently, on the public page.
        """
        script = page[page.rindex("<script>"):]
        for ident in re.findall(r"document\.getElementById\('([^']+)'\)", script):
            assert f'id="{ident}"' in page, (
                f"the filter reads #{ident}, which the page does not contain")
        declared = set(re.findall(r"const (\w+)\s*=", script))
        used = set(re.findall(r"!(\w+)\s*\|\|", script))
        assert used <= declared, (
            f"filterTable() reads {sorted(used - declared)} without declaring it; "
            f"that is the ReferenceError that broke the previous page")
